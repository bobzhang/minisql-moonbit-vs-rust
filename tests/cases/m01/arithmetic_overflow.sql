-- 64-bit integer overflow in + - * switches to REAL (no error).

SELECT 9223372036854775807 + 1, typeof(9223372036854775807 + 1);
SELECT 9223372036854775807 + 0, typeof(9223372036854775807 + 0);
SELECT -9223372036854775808 - 1, typeof(-9223372036854775808 - 1);
SELECT 9223372036854775807 - -1;
SELECT 9223372036854775807 * 2, -9223372036854775807 * 2;
SELECT 3037000500 * 3037000500, typeof(3037000500 * 3037000500);
-- Exactly the minimum is still INTEGER.
SELECT 4611686018427387904 * -2, typeof(4611686018427387904 * -2);
SELECT -4611686018427387904 * 2;
-- Negating the minimum integer overflows to REAL.
SELECT -(-9223372036854775807 - 1), typeof(-(-9223372036854775807 - 1));
SELECT -9223372036854775808 * -1;
-- Dividing the minimum integer by -1 overflows to REAL; the remainder is 0.
SELECT (-9223372036854775807 - 1) / -1, (-9223372036854775807 - 1) % -1;
-- Overflow mid-expression: once REAL, stays REAL.
SELECT 9223372036854775807 + 1 - 1, typeof(9223372036854775807 + 1 - 1);
SELECT (9223372036854775807 + 10) - 9223372036854775807;
-- Values near the limit that do not overflow.
SELECT 9223372036854775806 + 1, -9223372036854775807 - 1;
SELECT 4611686018427387903 * 2, 4611686018427387903 + 4611686018427387904;
-- Overflow with column values.
CREATE TABLE big(v INTEGER);
INSERT INTO big VALUES (9223372036854775807), (-9223372036854775808), (1);
SELECT v, v + 1, typeof(v + 1), v - 1, typeof(v - 1), v * 3, typeof(v * 3) FROM big ORDER BY v;
