SELECT id FROM t WHERE a IS NULL ORDER BY id;
SELECT id FROM t WHERE a IS NOT NULL ORDER BY id;
SELECT id FROM t WHERE a ISNULL ORDER BY id;
SELECT id FROM t WHERE b NOTNULL ORDER BY id;
SELECT id FROM t WHERE b NOT NULL ORDER BY id;
SELECT id FROM t WHERE a IS NULL AND b IS NULL ORDER BY id;
SELECT id FROM t WHERE a IS NULL OR b IS NULL ORDER BY id;
SELECT id FROM t WHERE a || b IS NOT NULL ORDER BY id;
