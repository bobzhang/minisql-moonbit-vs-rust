-- INTEGER vs REAL comparison is exact: large integers are not simply
-- converted to double before comparing.

SELECT 1 = 1.0, 1 < 1.0000001, 2 > 1.9999999;
-- 2^53 + 1 is not representable as a double.
SELECT 9007199254740993 = 9007199254740992.0;
SELECT 9007199254740993 > 9007199254740992.0;
SELECT 9007199254740992 = 9007199254740992.0;
-- The largest integer vs the double 2^63.
SELECT 9223372036854775807 = 9223372036854775807.0;
SELECT 9223372036854775807 < 9223372036854775807.0;
SELECT 9223372036854775806 < 9223372036854775807.0;
SELECT -9223372036854775808 = -9223372036854775808.0;
SELECT -9223372036854775807 > -9223372036854775808.0;
-- Values beyond the integer range.
SELECT 9223372036854775807 < 1e19, -9223372036854775808 > -1e19;
-- Infinities compare with integers.
SELECT 9223372036854775807 < 1e999, -9223372036854775808 > -1e999;
-- Fractional values between integers.
SELECT 3 < 3.5, 4 > 3.5, -3 > -3.5, -4 < -3.5;
-- In a table (untyped column keeps the class).
CREATE TABLE t(id INTEGER, v);
INSERT INTO t VALUES (1, 9007199254740993), (2, 9007199254740992.0), (3, 9007199254740992), (4, 1.5), (5, 1), (6, 2);
SELECT id FROM t WHERE v = 9007199254740992 ORDER BY id;
SELECT id FROM t WHERE v > 9007199254740992.0 ORDER BY id;
SELECT id FROM t WHERE v < 2 ORDER BY id;
SELECT id FROM t WHERE v >= 1.5 AND v < 1e10 ORDER BY id;
-- Integers and reals interleave by value when sorting.
SELECT v FROM t ORDER BY v, id;
